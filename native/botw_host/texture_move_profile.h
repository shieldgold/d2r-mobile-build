/* Only mapped executable module ranges are passed here. Runtime owns their
 * lifetime until every guest worker has joined and checked graphics retires.
 * No guest object/stack/heap contents or VM metadata are inspected. */
static inline int botw_texture_move_context_matches(const unsigned char *base,
        size_t image_bytes, size_t region_begin, size_t region_end,
        const botw_texture_move_context *context) {
    if (!base || !context || !context->bytes || context->bytes > UINT32_MAX ||
            region_begin > region_end || region_end > image_bytes ||
            context->offset < region_begin || context->offset > region_end ||
            context->bytes > region_end-context->offset) return 0;
    unsigned char digest[CC_SHA256_DIGEST_LENGTH];
    CC_SHA256(base+context->offset,(CC_LONG)context->bytes,digest);
    return !memcmp(digest,context->sha256,sizeof digest);
}
