#include <sys/mman.h>
#include <libkern/OSCacheControl.h>

#if defined(BOTW_PROBE_COUNT)
static jmp_buf allocation_escape;
static int executable_allocation_attempted;
static void *deny_mmap(void *a, size_t n, int p, int f, int fd, off_t o) {
    (void)a; (void)n; (void)p; (void)f; (void)fd; (void)o;
    executable_allocation_attempted++;
    longjmp(allocation_escape, 1); /* No memory allocation or generated bytes. */
}
#define mmap deny_mmap
#include "hle_count.c"
#undef mmap
int main(void) {
    static unsigned char owned_function_identity;
    setenv("DM_HLECOUNT", "/owned-fixture-unused.tsv", 1);
    if (!setjmp(allocation_escape)) {
        assert(hlecount_wrap((const char *)1, (const char *)1,
                             &owned_function_identity) == &owned_function_identity);
        hlecount_seal(); hlecount_svc(1); hlecount_flush();
    }
    if (executable_allocation_attempted) {
        fputs("FAIL: counting reached allocation before policy refusal\n", stderr);
        return 1;
    }
    puts("PASS: no allocation, code generation or executable permission change");
    return 0;
}
#elif defined(BOTW_PROBE_ENV)
#include "whole_policy.h"
int main(int argc, char **argv) {
    if (argc > 1 && !strcmp(argv[1], "backtrace")) {
        assert(backtrace((void **)1, 100) == 0);
        backtrace_symbols_fd((void *const *)1, 100, -1);
        return 0;
    }
    if (argc > 1 && !strcmp(argv[1], "denial"))
        botw_backend_host_diagnostic_denied((const char *)1);
    assert(!botw_backend_compat_diagnostic_enabled());
    for (int i = 1; i < argc; i++) {
        const char *value = getenv(argv[i]);
        puts(value ? value : "<NULL>");
    }
    return 0;
}
#else
#include "crash.c"
module_t *module_of(const void *p) { (void)p; return NULL; }
static int callbacks;
static unsigned char owned_memory[32];
static void owned_callback(void) { callbacks++; }
static void owned_write(void *p, size_t n) {
    assert(p == owned_memory && n == sizeof owned_memory); callbacks++;
}
static int owned_fault(void *p, int write, void *uc) {
    assert(p == owned_memory && write == 1 && uc); callbacks++; return 1;
}
int main(int argc, char **argv) {
    assert(argc == 2);
    if (!strcmp(argv[1], "dump")) {
        /* Directly seed only self-owned callbacks, so the baseline can safely
         * show the missing refusal without registering guest diagnostics. */
        g_dump_hook = owned_callback; g_wait_dump = owned_callback;
        crash_dump_now("self-owned CPU fixture");
        if (callbacks) { fputs("FAIL: diagnostic callbacks executed\n", stderr); return 1; }
        return 0;
    }
    if (!strcmp(argv[1], "write")) {
        dm_guest_write_prep_register(owned_write);
        dm_guest_write_prepare(owned_memory, sizeof owned_memory);
        assert(callbacks == 1); return 0;
    }
    if (!strcmp(argv[1], "fault") || !strcmp(argv[1], "unhandled")) {
        struct __darwin_mcontext64 owned_mc = {0};
        ucontext_t owned_uc = {0}; owned_uc.uc_mcontext = &owned_mc;
        owned_mc.__es.__esr = 1u << 6;
        siginfo_t owned_si = {0}; owned_si.si_addr = owned_memory;
        if (!strcmp(argv[1], "fault")) dm_fault_hook_register(owned_fault);
        on_crash(SIGSEGV, &owned_si, &owned_uc);
        assert(callbacks == 1); return 0;
    }
    if (!strcmp(argv[1], "register")) { crash_set_dump_hook(owned_callback); return 4; }
    if (!strcmp(argv[1], "wait")) { crash_set_wait_dump(owned_callback); return 4; }
    if (!strcmp(argv[1], "trap")) { crash_set_trap_hook(NULL); return 4; }
    if (!strcmp(argv[1], "backtrace")) { dm_backtrace(1); return 4; }
    if (!strcmp(argv[1], "offset")) { crash_off((const char *)1, 1); return 4; }
    return 5;
}
#endif
